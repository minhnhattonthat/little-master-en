"""Generate tbl/en.tbl: ASCII 20-7E (minus []{} = script syntax; 2A 3B 3C 3E 40 = the game's × ∶ ◀ ▶ ©)
+ every control code of jp.tbl."""
from pathlib import Path


def main():
    ctrl = [l for l in Path("tbl/jp.tbl").read_text(encoding="utf-8").splitlines()
            if "={" in l and not l.startswith("#")]
    ui = {0x2A: "×", 0x3B: "∶", 0x3C: "◀", 0x3E: "▶", 0x40: "©"}   # game font draws these codes as UI symbols
    chars = [f"{c:02X}={ui.get(c, chr(c))}" for c in range(0x20, 0x7F) if chr(c) not in "[]{}"]
    head = ["# Little Master EN table (generated by python -m lmtools.mk_en_tbl). ASCII + jp.tbl control codes."]
    Path("tbl/en.tbl").write_text("\n".join(head + chars + ctrl) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
